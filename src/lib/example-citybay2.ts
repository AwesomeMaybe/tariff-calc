import type { BuildingParams, CostSection, CostItem, StaffRole } from "@/types/tariff";

/**
 * Пример объекта — ЖК City Bay 2 (Алматы).
 * ТЭП и статьи затрат перенесены из реального расчёта тарифа УК
 * («Форма тарифа (2).xlsx», листы «Расчет» / «ТЭП» / «ФОТ»).
 *
 * Методология исходника: почти каждая статья — это норматив ₽/м² × общая
 * площадь объекта (перенесено как material/perArea — статья живая, пересчитывается
 * при изменении площади). ФОТ считается отдельно от реального штатного расписания
 * (лист «ФОТ»): оклад на руки → оклад gross (÷0.87 на ИПН) × штат, дальше общие
 * налоги/страховые взносы объекта (insuranceRate = 29.6%, посчитано из
 * налоги/ФОТ листа «ФОТ» — Σ ФОТ 1 833 333.33, Σ налоги 542 666.67).
 * Доп.услуги на подряде (контроль, консьерж, беллмен, доп.клининг, альпработы) —
 * тоже нормативы ₽/м², но с флагом vatOnly: цена подрядчика уже включает
 * платформу и наценку УК, сверху добавляется только НДС.
 *
 * Итоговый тариф по этой модели ≈ 184 ₽/м² (эксель — 185.01 ₽/м², разница
 * из-за единого коэффициента платформы/наценки вместо построчных долей эксель-файла).
 */

const AREA = 79537.23; // площадь для нормативов ₽/м² (= areaResidential+areaNonResidential+areaStorage+areaParkingSpots)

function perArea(id: string, label: string, rate: number, group: string, vatOnly?: boolean): CostItem {
  return { kind: "material", id, label, mode: "perArea", value: rate, area: AREA, group, vatOnly };
}

function role(oklad: number, headcount: number): StaffRole {
  return { type: "fixed", oklad, shiftsPerMonth: 21, headcount };
}

function fot(id: string, label: string, oklad: number, headcount: number, group: string): CostItem {
  return { kind: "labor", id, label, role: role(oklad, headcount), group };
}

function fixed(id: string, label: string, monthly: number, group: string, vatOnly?: boolean): CostItem {
  return { kind: "manual", id, label, monthly, group, vatOnly };
}

function toItem(id: string, label: string, rate: number, qty: number, group: string): CostItem {
  return { kind: "to", id, label, rate, qty, group };
}

